function initVoiceSelector() {
    const toolbar = document.querySelector('.reader-controls');
    const select = document.createElement('select');
    select.id = 'voice-select';
    select.style.maxWidth = '120px';
    select.innerHTML = '<option value="">Auto Voice</option>';
    toolbar.insertBefore(select, document.getElementById('tts-btn'));
    
    select.addEventListener('change', (e) => {
        const voiceName = e.target.value;
        if (voiceName) {
            const voice = voices.find(v => v.name === voiceName);
            if (voice) {
                if (voice.lang.includes('bn')) selectedBengaliVoice = voice;
                else selectedEnglishVoice = voice;
            }
        } else {
            autoSelectVoices();
        }
    });

    function populateVoiceList() {
        voices = window.speechSynthesis.getVoices();
        select.innerHTML = '<option value="">Auto Voice</option>';
        
        const filteredVoices = voices.filter(v => {
            const lang = v.lang.toLowerCase();
            if (lang.includes('bn-bd')) return false; // Exclude Bangladeshi
            return lang.includes('bn-in') || lang.includes('en-in') || lang.includes('en-gb') || lang.includes('en-us') || lang.includes('bn');
        });

        filteredVoices.forEach(voice => {
            const option = document.createElement('option');
            option.value = voice.name;
            option.textContent = `${voice.name} (${voice.lang})`;
            select.appendChild(option);
        });
        autoSelectVoices();
    }

    function autoSelectVoices() {
        if (!selectedEnglishVoice) {
            selectedEnglishVoice = voices.find(v => v.lang.toLowerCase().includes('en-in')) || 
                                   voices.find(v => v.lang.toLowerCase().includes('en-gb')) || 
                                   voices.find(v => v.lang.toLowerCase().includes('en-us'));
        }
        if (!selectedBengaliVoice) {
            selectedBengaliVoice = voices.find(v => v.lang.toLowerCase().includes('bn-in')) || 
                                    voices.find(v => v.lang.toLowerCase().includes('bn'));
        }
    }

    populateVoiceList();
    if (speechSynthesis.onvoiceschanged !== undefined) {
        speechSynthesis.onvoiceschanged = populateVoiceList;
    }
}

function stopTTS() {
    window.speechSynthesis.cancel();
    ttsQueue = [];
    isSpeaking = false;
    document.getElementById('tts-btn').innerText = '▶ Read';
    document.querySelectorAll('.reading-now').forEach(el => el.classList.remove('reading-now'));
}

function toggleTTS() {
    if (isSpeaking) {
        stopTTS();
        return;
    }

    const page = lesson.pages[currentPageIndex];
    if (!page) return;

    ttsQueue = [];
    const elementsToRead = [];

    if (langMode === 'en' || langMode === 'both') {
        document.querySelectorAll('.en-text').forEach(el => elementsToRead.push({ element: el, lang: 'en' }));
    }
    if (langMode === 'bn' || langMode === 'both') {
        document.querySelectorAll('.bengali-text').forEach(el => elementsToRead.push({ element: el, lang: 'bn' }));
    }

    if (elementsToRead.length === 0) return;

    elementsToRead.forEach((item) => {
        const text = item.element.innerText;
        if (!text) return;
        const utterance = new SpeechSynthesisUtterance(text);
        if (item.lang === 'en') {
            utterance.voice = selectedEnglishVoice;
            utterance.lang = selectedEnglishVoice ? selectedEnglishVoice.lang : 'en-IN';
        } else {
            utterance.voice = selectedBengaliVoice;
            utterance.lang = selectedBengaliVoice ? selectedBengaliVoice.lang : 'bn-IN';
        }
        utterance.rate = 0.9;
        
        utterance.onstart = () => {
            item.element.classList.add('reading-now');
        };
        utterance.onend = () => {
            item.element.classList.remove('reading-now');
        };
        utterance.onerror = () => {
            item.element.classList.remove('reading-now');
        };
        ttsQueue.push(utterance);
    });

    isSpeaking = true;
    document.getElementById('tts-btn').innerText = '⏹ Stop';
    
    function playNext() {
        if (ttsQueue.length === 0) {
            stopTTS();
            return;
        }
        const utterance = ttsQueue.shift();
        utterance.onend = () => {
            utterance.element.classList.remove('reading-now');
            playNext();
        };
        window.speechSynthesis.speak(utterance);
    }
    playNext();
}

