    wordModal.addEventListener('click', (e) => {
        if (e.target === wordModal) wordModal.classList.add('hidden');
    });

    if ('serviceWorker' in navigator) {
        navigator.serviceWorker.register('sw.js').catch(err => console.log('SW registration failed'));
    }

    initVoiceSelector();
